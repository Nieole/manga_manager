// Package diskwork 把一次**磁盘作业**收进单一入口：调用方交出「干哪一类活、字节落在哪」与一个
// 闭包，本包过**暂停闸门**、解析存储策略、按工种定并发上限、申领与归还**存储令牌**、观测过久的
// 等待，并把等待与暂停的耗时作为返回值交回。
//
// 三条契约由结构而非调用方的记性保证：闸门必然先于令牌，被暂停的作业不会攥着令牌堵死别人；令牌
// 的归还不依赖闭包走哪条出口，panic 时同样已归还；能并发几个只由工种决定，与调用方是谁无关。
//
// 边界：Stats 是返回值，本包不持有也不上报指标。令牌的排队规则、阅读优先与后台整体暂停属于
// storageio，暂停闸门属于 taskcontrol，策略与卷键的推导属于 config；前台的阅读取页不是磁盘
// 作业，仍直接向 storageio.Scheduler 申领。
