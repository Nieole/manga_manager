//
// 三条契约由结构而非调用方的记性保证：过闸门在未暂停时返回上下文错误，因此它同时是取消检查；
// 磁盘作业的实况在入口自己折进累加器，取用不依赖调用方记得吸收；「已哈希文件数」只在工种是
// 整文件读取**且闭包真的执行了**时才 +1。全部方法可从任意 goroutine 调用。
//
// 边界：句柄由 api 的任务引擎构造并交给任务体，跨包的批循环只经它们自己声明的窄接口看见它；
// 本包不认识**任务键**、**作用域**与**终态**，它们属于任务引擎；一帧上报怎么落库、怎么投递
